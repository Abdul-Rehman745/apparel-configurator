// Generates docs/mesh-spec.md -- the meshes a GLB must contain to replace each catalog garment model.
// Built from the live seed catalog (via the shared domain bundle), so names and sizes never drift.
//   npm run build:server && node scripts/mesh-spec.mjs
import { writeFile } from 'node:fs/promises'
import { defaultCatalog } from '../supabase/functions/_shared/domain.js'

const f1 = (n) => n.toFixed(1)
const PANEL_NOTES = {
  front: 'Outer front torso, collar to hem, side seam to side seam. Planar UV: U 0→1 = wearer\'s right→left as seen from the front (viewer\'s left→right); V 0 = collar/top in glTF.',
  back: 'Outer back torso. Planar UV **mirrored**: U 0→1 = viewer\'s left→right when seen from *behind*, so back prints read correctly.',
  back_inside: 'Inside face of the upper back (neck-label zone). Separate mesh, normals facing inward, UV readable from inside the neck. Only the top ~6" is needed.',
  left_sleeve: 'Wearer\'s left sleeve (viewer\'s right from the front). Cylindrical UV around the sleeve axis: outer face centred at U=0.5, seam on the underarm, V 0 = shoulder.',
  right_sleeve: 'Wearer\'s right sleeve. Same rules as the left; U runs toward the viewer\'s right when the sleeve is seen from outside.',
  left_cuff: 'Rib cuff band on the left sleeve end. Cylindrical UV, outer face centred at U=0.5.',
  right_cuff: 'Rib cuff band on the right sleeve end. Same rules as the left cuff.',
  collar: 'Collar band. U runs around the neck starting at the front opening; the back of the collar sits at U=0.5.',
}

function trims(g) {
  if (!g) return []
  const t = []
  if (g.collar === 'crew' || g.collar === 'v') t.push(['shirt_neck_rib', 'Neck rib band (not printable)'])
  if (g.collar === 'hood') t.push(['shirt_hood_left', "Hood half on the wearer's left (sewn to the right half along the back seam)"], ['shirt_hood_right', "Hood half on the wearer's right"])
  if (g.placket) {
    const n = g.collar === 'dress' ? 7 : 3
    t.push(['shirt_placket', 'Button placket strip topstitched to the front'], [`shirt_button_01 … shirt_button_0${n}`, `${n} buttons, placed on the settled placket`])
  }
  if (g.pocket) t.push(['shirt_pocket', 'Kangaroo pocket patch with open hand slots (front print areas already avoid it)'])
  if (g.kind === 'hoodie' || (g.kind === 'longsleeve' && g.cuffs)) t.push(['shirt_hem_rib', 'Hem rib band'])
  return t
}

let md = `# GLB mesh specification per garment

Generated by \`scripts/mesh-spec.mjs\` from the seed catalog — do not edit by hand.

## Rules that apply to every model

- **One mesh per printable panel**, named as in the tables (the admin maps panel → mesh by name; these are the recommended names and what \`models/prepare_tshirt.py\` produces).
- **Orientation:** glTF Y-up, garment facing **+Z**, hem at Y=0, centred on X/Z. Units in metres or inches (the app rescales by the tallest panel's height).
- **UVs:** each printable mesh has its own non-overlapping 0–1 UV square that is roughly **isometric** (1 UV unit = the panel's W or H in real inches, no stretch). glTF convention: V=0 at the top.
- **Panel size** = the real-world inches that panel's UV square covers. The numbers below are the reference sizes of the current procedural models; for a GLB, measure your own mesh and enter those values in \`/admin → Products → 3D models\`.
- **Trims** (rib, placket, buttons, hood, pocket) are separate, unprintable meshes. Their materials are replaced at runtime (fabric/colour), so baked textures are not needed.
- **Colour zone** = which garment colour the panel takes when the product allows separate colours per zone.
- **Verify** every model with the in-app checker (\`/?product=<id>&model=<id>&checker=<areaId>\`) and \`e2e/real-model.spec.ts\`-style UV orientation checks before publishing.
- **Budget:** ≤ 50k triangles per garment, Draco or Meshopt compression.

`

for (const p of defaultCatalog.products) {
  md += `\n## ${p.title} (\`${p.id}\`)\n`
  for (const m of p.models) {
    const g = m.source.garment ?? null
    md += `\n### Model: ${m.label} (\`${m.id}\`) — ${m.source.type === 'glb' ? `GLB \`${m.source.url}\`${g ? ' (sewn by `models/sew_garment.py`)' : ''}` : 'procedural reference'}\n\n`
    if (g) md += `Shape: ${g.kind}, ${g.collar} collar, chest ${g.chestIn}" flat, length ${g.lengthIn}", sleeve ${g.sleeveLengthIn}"${g.placket ? ', placket' : ''}${g.pocket ? ', pocket' : ''}${g.cuffs ? ', cuffs' : ''}.\n\n`
    md += `**Printable meshes**\n\n| Mesh name | Panel | UV square (W × H in) | Colour zone | Print areas on it | Notes |\n|---|---|---|---|---|---|\n`
    for (const panel of m.panels) {
      const areas = m.printAreas.filter((a) => a.panel === panel.id)
        .map((a) => `${a.label} ${f1(a.rect.wIn)}×${f1(a.rect.hIn)}" @ (${f1(a.rect.xIn)}, ${f1(a.rect.yIn)})`).join('<br>') || '—'
      md += `| \`${panel.mesh ?? `shirt_${panel.id}`}\` | ${panel.id} | ${f1(panel.widthIn)} × ${f1(panel.heightIn)} | ${panel.colorZone} | ${areas} | ${PANEL_NOTES[panel.id] ?? ''} |\n`
    }
    const tr = trims(g)
    if (tr.length) md += `\n**Trim meshes (not printable)**\n\n| Mesh name | Purpose |\n|---|---|\n` + tr.map(([n, d]) => `| \`${n}\` | ${d} |`).join('\n') + '\n'
    if (m.source.type === 'glb') md += `\nLicence: ${m.license.license} — ${m.license.author} (${m.license.url}).\n`
  }
}
md += `\nPrint-area positions are the area's top-left corner in inches from the panel's top-left.\n`
await writeFile('docs/mesh-spec.md', md)
console.log('wrote docs/mesh-spec.md')
